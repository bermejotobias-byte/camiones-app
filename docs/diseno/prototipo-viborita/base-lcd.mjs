const LCD = { fondo: ['#b8d27a', '#97b555'], tinta: '#1b2412', sombra: 'rgba(27,36,18,.2)', fantasma: 'rgba(27,36,18,.07)' };

function lcd(ancho, alto, dibujo) {
  const id = `l${Math.random().toString(36).slice(2, 7)}`;
  const px = [];
  const on = (x, y) => px.push([x, y]);
  const d = {
    sprite(n, x, y) { S[n].forEach((f, j) => [...f].forEach((c, i) => c === '#' && on(x + i, y + j))); },
    texto(t, x, y, k = 1) {
      let cx = x;
      for (const ch of String(t)) {
        F[ch].forEach((f, j) => [...f].forEach((c, i) => { if (c === '#') for (let a = 0; a < k; a++) for (let b = 0; b < k; b++) on(cx + i * k + a, y + j * k + b); }));
        cx += 6 * k;
      }
    },
    ancho: (t, k = 1) => String(t).length * 6 * k - k,
    centro(t, y, k = 1) { this.texto(t, Math.round((ancho - this.ancho(t, k)) / 2), y, k); },
    linea(x0, y0, x1, y1) { for (let x = x0; x <= x1; x++) for (let y = y0; y <= y1; y++) on(x, y); },
    marco(x0, y0, x1, y1) { this.linea(x0, y0, x1, y0); this.linea(x0, y1, x1, y1); this.linea(x0, y0, x0, y1); this.linea(x1, y0, x1, y1); },
    // La barrita de senal y la pila del modo de espera: van arriba en todas las pantallas.
    estado() {
      [2, 3, 4, 5].forEach((h, i) => this.linea(1 + i * 2, 7 - h, 1 + i * 2, 6));
      this.marco(ancho - 9, 1, ancho - 2, 6); this.linea(ancho - 1, 3, ancho - 1, 4); this.linea(ancho - 8, 2, ancho - 3, 5);
    },
    teclas(izq, der) { this.texto(izq, 2, alto - 8); this.texto(der, ancho - this.ancho(der) - 2, alto - 8); }
  };
  dibujo(d);
  const W = ancho * P, H = alto * P;
  return `<svg viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" style="display:block;shape-rendering:crispEdges">
    <defs><linearGradient id="${id}g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${LCD.fondo[0]}"/><stop offset="1" stop-color="${LCD.fondo[1]}"/></linearGradient>
      <pattern id="${id}p" width="${P}" height="${P}" patternUnits="userSpaceOnUse"><path d="M${P} 0V${P}H0" fill="none" stroke="${LCD.fantasma}" stroke-width=".6"/></pattern>
      <radialGradient id="${id}v" cx=".5" cy=".45" r=".75"><stop offset=".6" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity=".22"/></radialGradient></defs>
    <rect width="${W}" height="${H}" fill="url(#${id}g)"/><rect width="${W}" height="${H}" fill="url(#${id}p)"/>
    ${px.map(([x, y]) => `<rect x="${(x + 1) * P}" y="${(y + 1) * P}" width="${P}" height="${P}" fill="${LCD.sombra}"/>`).join('')}
    ${px.map(([x, y]) => `<rect x="${x * P}" y="${y * P}" width="${P}" height="${P}" fill="${LCD.tinta}"/>`).join('')}
    <rect width="${W}" height="${H}" fill="url(#${id}v)"/>
  </svg>`;
}


